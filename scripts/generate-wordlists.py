#!/usr/bin/env python3
"""Fetches EFF's large wordlist (CC-BY 4.0) and writes it as a Swift array in
Packages/Derivation/Sources/Derivation, verbatim. An entry is chosen as an 8-byte block
modulo the list size, so the order is part of every password ever derived with the list.

Run:  python3 scripts/generate-wordlists.py   (standard library only)
"""

import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Packages" / "Derivation" / "Sources" / "Derivation"

EFF_URL = "https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt"


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def swift_header(origin):
    return (
        "//\n"
        "//  Generated by scripts/generate-wordlists.py; do not edit by hand.\n"
        f"//  {origin}\n"
        "//  The order is part of every password derived with this list and cannot change.\n"
        "//\n\n"
    )


def main():
    lines = fetch(EFF_URL).splitlines()
    words = [line.split("\t")[1] for line in lines if "\t" in line]
    if len(words) != 7776 or len(set(words)) != 7776:
        sys.exit(f"expected 7776 unique EFF words, got {len(words)}")
    rows = [", ".join(f'"{w}"' for w in words[i : i + 8]) for i in range(0, len(words), 8)]
    body = "let effLargeWords: [String] = [\n    " + ",\n    ".join(rows) + "\n]\n"
    path = OUT / "WordLists+EFF.swift"
    path.write_text(swift_header(f"Source: {EFF_URL} (EFF large wordlist, 2016-07-19, CC-BY 4.0).") + body)
    print(f"wrote {path.relative_to(ROOT)} ({len(words)} words)")


if __name__ == "__main__":
    main()
